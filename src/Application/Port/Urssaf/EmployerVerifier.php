use TheBeardedBear\UrssafTierceDeclarationPaje\Domain\Shared\TenantId;

/**
 * Operation 020: reads the state of the online account of an employer (api-reference §2). A read, safe to retry.
 */
interface EmployerVerifier
{
    /**
     * Verifies the employer (Pajemploi number and birth date) and returns the state of its online account.
     *
     * @throws UrssafRequestRejected      HTTP 400, classified ({@see RejectionKind})
     * @throws UrssafAuthenticationFailed
     * @throws UrssafUnavailable          retryable (transport error, 429, 5xx)
     * @throws RateLimitExceeded          the local limiter refused the call
     *
     * Any other {@see UrssafException} means URSSAF answered something the contract does not describe.
     */
    public function verifyEmployer(TenantId $tenantId, #[SensitiveParameter] EmployerReference $employer): EmployerVerification;
}
